//! The oracle self-test (docs/02-oracle.md section 5, item 5).
//!
//! Two built-in stub mergers, one returning `ours` and one returning `base`,
//! are run through the same classifier as real results. On a case where both
//! are wrong they must be classed `resolved-wrong` by the L2 comparison, so a
//! classifier that stops comparing to `expected` cannot pass the gate. Control
//! results (`expected`, a refusal) must not be classed wrong, so a classifier
//! that calls everything wrong cannot pass either.

use crate::classify::{CaseView, Class, Kind, Run, Verdict, classify, foreign_ids, kind_of};
use crate::oracle::{CargoOracle, Oracle};

const HEAD: &str = "# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n\n";

/// A canonical Cargo.lock: `app` depends on every package named.
fn lock(names: &[&str]) -> Vec<u8> {
    let mut s = String::from(HEAD);
    s.push_str("[[package]]\nname = \"app\"\nversion = \"0.1.0\"\n");
    if !names.is_empty() {
        s.push_str("dependencies = [\n");
        for n in names {
            s.push_str(&format!(" \"{n}\",\n"));
        }
        s.push_str("]\n");
    }
    for n in names {
        s.push_str(&format!(
            "\n[[package]]\nname = \"{n}\"\nversion = \"1.0.0\"\nsource = \"registry+x\"\nchecksum = \"{n}\"\n"
        ));
    }
    s.into_bytes()
}

/// A stub merger: bytes in, the run a driver would have produced.
type Stub = fn(base: &[u8], ours: &[u8], theirs: &[u8]) -> Run;

fn stub_ours(_: &[u8], ours: &[u8], _: &[u8]) -> Run {
    Run::Clean(ours.to_vec())
}

fn stub_base(base: &[u8], _: &[u8], _: &[u8]) -> Run {
    Run::Clean(base.to_vec())
}

/// The classifier under test.
pub type Classifier = fn(&dyn Oracle, &CaseView, &Run, &Run) -> Verdict;

pub fn run() -> Result<(), String> {
    run_with(classify)
}

pub fn run_with(classify: Classifier) -> Result<(), String> {
    let o = CargoOracle;
    let (base, ours, theirs) = (lock(&["pa"]), lock(&["pa", "pb"]), lock(&["pa", "pc"]));
    let expected = lock(&["pa", "pb", "pc"]);

    // The inputs and the expected result must themselves be sound.
    for (name, b) in [
        ("base", &base),
        ("ours", &ours),
        ("theirs", &theirs),
        ("expected", &expected),
    ] {
        o.canonical(b)
            .map_err(|e| format!("self-test fixture {name} is not canonical: {e}"))?;
        o.valid(b)
            .map_err(|e| format!("self-test fixture {name} is not valid: {e}"))?;
    }
    let foreign = foreign_ids(&o, &base, &ours, &theirs, &expected)?;
    if kind_of(&foreign) != Kind::Reachable {
        return Err("self-test: the built-in case is not reachable".into());
    }
    let view = CaseView {
        kind: Kind::Reachable,
        expected: &expected,
        waiver: None,
    };

    // Both stubs are wrong here and must be caught by L2 specifically.
    for (name, stub) in [
        ("return ours", stub_ours as Stub),
        ("return base", stub_base),
    ] {
        let r = stub(&base, &ours, &theirs);
        let v = classify(&o, &view, &r, &r);
        if v.class != Class::ResolvedWrong || v.detail != "L2: differs from expected" {
            return Err(format!(
                "self-test: stub `{name}` was classed {} ({}), not resolved-wrong by L2",
                v.class.name(),
                v.detail
            ));
        }
    }

    // Controls: the right answer is correct, a refusal is a refusal.
    let right = Run::Clean(expected.clone());
    let v = classify(&o, &view, &right, &right);
    if v.class != Class::ResolvedCorrect {
        return Err(format!(
            "self-test: the expected result was classed {}",
            v.class.name()
        ));
    }
    let v = classify(&o, &view, &Run::Refused, &Run::Refused);
    if v.class != Class::Refused {
        return Err(format!(
            "self-test: a refusal was classed {}",
            v.class.name()
        ));
    }

    // A re-resolved case: a refusal is correct, a stub's resolution is never.
    let fresh = lock(&["pa", "pb", "pc", "pd"]);
    let foreign = foreign_ids(&o, &base, &ours, &theirs, &fresh)?;
    if kind_of(&foreign) != Kind::ReResolved {
        return Err("self-test: the built-in re-resolved case is not re-resolved".into());
    }
    let view = CaseView {
        kind: Kind::ReResolved,
        expected: &fresh,
        waiver: None,
    };
    let v = classify(&o, &view, &Run::Refused, &Run::Refused);
    if v.class != Class::RefusedCorrect {
        return Err(format!(
            "self-test: a re-resolved refusal was classed {}",
            v.class.name()
        ));
    }
    let r = stub_ours(&base, &ours, &theirs);
    let v = classify(&o, &view, &r, &r);
    if v.class == Class::ResolvedCorrect || v.class == Class::RefusedCorrect {
        return Err(format!(
            "self-test: a stub's resolution of a re-resolved case was classed {}",
            v.class.name()
        ));
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use crate::classify::{CaseView, Class, Run, Verdict};
    use crate::oracle::Oracle;

    #[test]
    fn the_self_test_passes() {
        super::run().unwrap();
    }

    fn says(class: Class) -> Verdict {
        Verdict {
            class,
            detail: "L2: differs from expected".into(),
        }
    }

    #[test]
    fn a_classifier_that_trusts_every_merge_fails_the_self_test() {
        fn lenient(_: &dyn Oracle, _: &CaseView, run: &Run, _: &Run) -> Verdict {
            match run {
                Run::Clean(_) => says(Class::ResolvedCorrect),
                _ => says(Class::Refused),
            }
        }
        assert!(
            super::run_with(lenient)
                .unwrap_err()
                .contains("not resolved-wrong")
        );
    }

    #[test]
    fn a_classifier_that_condemns_every_merge_fails_the_self_test() {
        fn harsh(_: &dyn Oracle, _: &CaseView, run: &Run, _: &Run) -> Verdict {
            match run {
                Run::Clean(_) => says(Class::ResolvedWrong),
                _ => says(Class::Refused),
            }
        }
        assert!(
            super::run_with(harsh)
                .unwrap_err()
                .contains("expected result was classed")
        );
    }
}
