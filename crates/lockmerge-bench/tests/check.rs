//! End-to-end tests of `check`: real `git merge` in temporary repositories,
//! with a fake `lockmerge` driver script standing in for the real binary
//! (`lockmerge-cli`, #34, does not exist yet). Unix only: the driver is a
//! shell script.
#![cfg(unix)]

use lockmerge_bench::check::{CheckOpts, CheckOutcome, check};
use lockmerge_bench::util::{TempDir, sha256_hex};
use lockmerge_core::{
    CodeDef, Context, Error, Format, FormatId, Inputs, Outcome, ReasonCode, Refusal, Report,
    RuleDef,
};
use std::fs;
use std::os::unix::fs::PermissionsExt;
use std::path::{Path, PathBuf};

const HEAD: &str = "# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n\n";

/// A canonical Cargo.lock: `app` depends on every (name, checksum) package.
fn lock(pkgs: &[(&str, &str)]) -> Vec<u8> {
    let mut s = String::from(HEAD);
    s.push_str("[[package]]\nname = \"app\"\nversion = \"0.1.0\"\n");
    if !pkgs.is_empty() {
        s.push_str("dependencies = [\n");
        for (n, _) in pkgs {
            s.push_str(&format!(" \"{n}\",\n"));
        }
        s.push_str("]\n");
    }
    for (n, c) in pkgs {
        s.push_str(&format!(
            "\n[[package]]\nname = \"{n}\"\nversion = \"1.0.0\"\nsource = \"registry+x\"\nchecksum = \"{c}\"\n"
        ));
    }
    s.into_bytes()
}

struct Fixtures {
    root: TempDir,
}

const BASELINE: &str = "min_cases = 0\nmin_reachable = 0\nmin_rate_resolved = 0\nmin_rate_of = 1\nmax_unverified = 0\nmax_regressions = 0\n";

impl Fixtures {
    fn new(baseline: &str) -> Fixtures {
        let root = TempDir::new("fixtures").unwrap();
        let eco = root.path().join("cargo");
        fs::create_dir_all(&eco).unwrap();
        fs::write(eco.join("INDEX.toml"), "").unwrap();
        fs::write(eco.join("baseline.toml"), baseline).unwrap();
        Fixtures { root }
    }

    fn add(&self, sha: &str, kind: &str, [base, ours, theirs, expected]: [&[u8]; 4]) -> PathBuf {
        let dir = self.root.path().join("cargo/owner-repo").join(sha);
        fs::create_dir_all(dir.join("manifests/base")).unwrap();
        let manifest = b"[package]\nname = \"app\"\n";
        let mut toml = format!(
            "repository = \"https://example.invalid/r\"\nlicense = \"MIT\"\nlockfile_path = \"Cargo.lock\"\nours_is = \"parent1\"\nkind = \"{kind}\"\n[sha256]\n"
        );
        let files: [(&str, &[u8]); 5] = [
            ("base", base),
            ("ours", ours),
            ("theirs", theirs),
            ("expected", expected),
            ("manifests/base/Cargo.toml", manifest),
        ];
        for (rel, bytes) in files {
            fs::write(dir.join(rel), bytes).unwrap();
            toml.push_str(&format!("\"{rel}\" = \"{}\"\n", sha256_hex(bytes)));
        }
        fs::write(dir.join("case.toml"), toml).unwrap();
        dir
    }
}

/// A fake `lockmerge` binary. `body` runs with `$2 $3 $4` = `%O %A %B`.
fn driver(body: &str) -> (TempDir, PathBuf) {
    let dir = TempDir::new("driver").unwrap();
    let bin = dir.path().join("lockmerge");
    fs::write(&bin, format!("#!/bin/sh\n{body}\n")).unwrap();
    fs::set_permissions(&bin, fs::Permissions::from_mode(0o755)).unwrap();
    (dir, bin)
}

/// A driver that always writes `bytes` into `%A` and exits 0.
fn writes(bytes: &[u8]) -> (TempDir, PathBuf) {
    let text = String::from_utf8(bytes.to_vec()).unwrap();
    driver(&format!(
        "cat > \"$3\" <<'LOCKMERGE_EOF'\n{text}LOCKMERGE_EOF\nexit 0"
    ))
}

fn run(fx: &Fixtures, bin: &Path, formats: &[&dyn Format]) -> CheckOutcome {
    let mut opts = CheckOpts::new(fx.root.path().to_path_buf());
    opts.driver_bin = Some(bin.to_path_buf());
    check(&opts, formats)
}

fn conflict_case() -> [Vec<u8>; 4] {
    [
        lock(&[("pa", "a")]),
        lock(&[("pa", "a"), ("pb", "b")]),
        lock(&[("pa", "a"), ("pc", "c")]),
        lock(&[("pa", "a"), ("pb", "b"), ("pc", "c")]),
    ]
}

/// Edits far enough apart that git's text merge is clean.
fn clean_case() -> [Vec<u8>; 4] {
    [
        lock(&[("pa", "a"), ("pb", "b")]),
        lock(&[("pa", "A"), ("pb", "b")]),
        lock(&[("pa", "a"), ("pb", "B")]),
        lock(&[("pa", "A"), ("pb", "B")]),
    ]
}

fn add(fx: &Fixtures, sha: &str, kind: &str, c: &[Vec<u8>; 4]) {
    fx.add(sha, kind, [&c[0], &c[1], &c[2], &c[3]]);
}

#[test]
fn a_driver_that_resolves_correctly_counts_in_the_headline() {
    let fx = Fixtures::new(
        "min_cases = 1\nmin_reachable = 1\nmin_rate_resolved = 1\nmin_rate_of = 1\nmax_unverified = 0\nmax_regressions = 0\n",
    );
    let c = conflict_case();
    add(&fx, "aaaaaaaaaaaa", "reachable", &c);
    let (_d, bin) = writes(&c[3]);
    let out = run(&fx, &bin, &[]);
    assert!(out.passed(), "{:?}", out.failures);
    let m = &out.ecosystems[0].metrics;
    assert_eq!((m.c_r, m.s_r, m.false_merges), (1, 1, 0));
    assert_eq!(m.exact, 1);
}

#[test]
fn a_valid_but_different_resolution_is_a_wrong_merge_and_fails_the_gate() {
    let fx = Fixtures::new(BASELINE);
    let c = conflict_case();
    add(&fx, "aaaaaaaaaaaa", "reachable", &c);
    // Valid and canonical, but it drops theirs' `pc`.
    let (_d, bin) = writes(&c[1]);
    let out = run(&fx, &bin, &[]);
    assert!(!out.passed());
    assert_eq!(out.ecosystems[0].metrics.false_merges, 1);
    assert!(out.failures.iter().any(|f| f.contains("wrong merge")));
}

#[test]
fn a_refusal_is_a_missed_opportunity_and_the_ratchet_catches_it() {
    let c = conflict_case();
    let fx = Fixtures::new(BASELINE);
    add(&fx, "aaaaaaaaaaaa", "reachable", &c);
    let (_d, bin) = driver("exit 1");
    let out = run(&fx, &bin, &[]);
    assert!(out.passed(), "{:?}", out.failures);
    let m = &out.ecosystems[0].metrics;
    assert_eq!((m.c_r, m.s_r, m.classes["refused"]), (1, 0, 1));

    // The same result against a baseline of 1 of 1 fails.
    let fx = Fixtures::new(
        "min_cases = 0\nmin_reachable = 0\nmin_rate_resolved = 1\nmin_rate_of = 1\nmax_unverified = 0\nmax_regressions = 0\n",
    );
    add(&fx, "aaaaaaaaaaaa", "reachable", &c);
    let out = run(&fx, &bin, &[]);
    assert!(
        out.failures
            .iter()
            .any(|f| f.contains("below the baseline"))
    );
}

#[test]
fn a_driver_that_crashes_is_an_error() {
    let fx = Fixtures::new(BASELINE);
    add(&fx, "aaaaaaaaaaaa", "reachable", &conflict_case());
    let (_d, bin) = driver("exit 255");
    let out = run(&fx, &bin, &[]);
    assert!(!out.passed());
    assert_eq!(
        out.ecosystems[0].metrics.errors, 1,
        "{:?}",
        out.ecosystems[0].results
    );
    assert_eq!(out.ecosystems[0].metrics.false_merges, 0);
}

#[test]
fn a_driver_that_hangs_is_an_error() {
    let fx = Fixtures::new(BASELINE);
    add(&fx, "aaaaaaaaaaaa", "reachable", &conflict_case());
    let (_d, bin) = driver("sleep 30");
    let mut opts = CheckOpts::new(fx.root.path().to_path_buf());
    opts.driver_bin = Some(bin);
    opts.timeout = std::time::Duration::from_millis(500);
    let out = check(&opts, &[]);
    assert!(!out.passed());
    assert_eq!(out.ecosystems[0].metrics.errors, 1);
    assert!(out.ecosystems[0].results[0].detail.contains("timeout"));
}

#[test]
fn the_swap_check_turns_order_dependent_guessing_into_an_error() {
    let fx = Fixtures::new(BASELINE);
    add(&fx, "aaaaaaaaaaaa", "reachable", &conflict_case());
    // Leaves `%A` (the current branch's side) unchanged: "take ours".
    let (_d, bin) = driver("exit 0");
    let out = run(&fx, &bin, &[]);
    assert!(!out.passed());
    let r = &out.ecosystems[0].results[0];
    assert_eq!(r.class.name(), "error");
    assert!(r.detail.contains("swap check"), "{}", r.detail);
}

#[test]
fn git_clean_cases_are_outside_the_headline_and_a_refusal_there_is_a_regression() {
    let fx = Fixtures::new(BASELINE);
    let c = clean_case();
    add(&fx, "aaaaaaaaaaaa", "reachable", &c);
    // Refusing where git alone is correct.
    let (_d, bin) = driver("exit 1");
    let out = run(&fx, &bin, &[]);
    let m = &out.ecosystems[0].metrics;
    assert_eq!(
        (m.c_r, m.s_r, m.regressions),
        (0, 0, 1),
        "{:?}",
        out.ecosystems[0].results
    );
    // Resolving correctly there is not a headline success either.
    let (_d, bin) = writes(&c[3]);
    let out = run(&fx, &bin, &[]);
    let m = &out.ecosystems[0].metrics;
    assert_eq!((m.c_r, m.s_r, m.regressions), (0, 0, 0));
    assert_eq!(m.resolved_correct_reachable, 1);
}

#[test]
fn the_regression_ratchet_fails_a_refusal_of_a_git_clean_case() {
    let c = clean_case();
    let (_d, refuses) = driver("exit 1");
    let (_e, resolves) = writes(&c[3]);
    // A baseline allowing none: refusing fails the gate, resolving passes.
    let fx = Fixtures::new(BASELINE);
    add(&fx, "aaaaaaaaaaaa", "reachable", &c);
    let out = run(&fx, &refuses, &[]);
    assert!(
        out.failures.iter().any(|f| f.contains("regressions")),
        "{:?}",
        out.failures
    );
    assert!(run(&fx, &resolves, &[]).passed());
    // A baseline allowing one accepts the refusal.
    let fx = Fixtures::new(&BASELINE.replace("max_regressions = 0", "max_regressions = 1"));
    add(&fx, "aaaaaaaaaaaa", "reachable", &c);
    assert!(run(&fx, &refuses, &[]).passed());
}

#[test]
fn a_re_resolved_case_must_be_refused() {
    let base = lock(&[("pa", "a")]);
    let ours = lock(&[("pa", "a"), ("pb", "b")]);
    let theirs = lock(&[("pa", "a"), ("pc", "c")]);
    // The committed resolution carries `pd`, which neither side had.
    let expected = lock(&[("pa", "a"), ("pb", "b"), ("pc", "c"), ("pd", "d")]);
    let c = [base, ours, theirs, expected];
    let fx = Fixtures::new(BASELINE);
    add(&fx, "aaaaaaaaaaaa", "re-resolved", &c);

    let (_d, bin) = driver("exit 1");
    let out = run(&fx, &bin, &[]);
    assert!(out.passed(), "{:?}", out.failures);
    assert_eq!(out.ecosystems[0].metrics.re_refused_correct, 1);
    // Excluded from the headline denominator.
    assert_eq!(out.ecosystems[0].metrics.c_r, 0);

    // A resolution is unverified, and the baseline allows none.
    let merged = lock(&[("pa", "a"), ("pb", "b"), ("pc", "c")]);
    let (_d, bin) = writes(&merged);
    let out = run(&fx, &bin, &[]);
    assert_eq!(out.ecosystems[0].metrics.unverified, 1);
    assert!(
        out.failures
            .iter()
            .any(|f| f.contains("resolved-unverified"))
    );

    // An invalid resolution of a re-resolved case is wrong.
    let (_d, bin) = writes(b"not a lockfile\n");
    let out = run(&fx, &bin, &[]);
    assert_eq!(out.ecosystems[0].metrics.false_merges, 1);
}

#[test]
fn a_case_cannot_be_moved_to_the_easier_class_by_editing_case_toml() {
    let fx = Fixtures::new(BASELINE);
    let base = lock(&[("pa", "a")]);
    let ours = lock(&[("pa", "a"), ("pb", "b")]);
    let theirs = lock(&[("pa", "a"), ("pc", "c")]);
    let expected = lock(&[("pa", "a"), ("pb", "b"), ("pc", "c"), ("pd", "d")]);
    // Truly re-resolved, but labeled reachable.
    add(
        &fx,
        "aaaaaaaaaaaa",
        "reachable",
        &[base, ours, theirs, expected],
    );
    let (_d, bin) = driver("exit 1");
    let out = run(&fx, &bin, &[]);
    assert!(
        out.failures
            .iter()
            .any(|f| f.contains("case.toml says reachable but the bytes say re-resolved"))
    );
}

