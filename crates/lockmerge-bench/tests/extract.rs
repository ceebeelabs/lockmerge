    assert!(c.problems.is_empty(), "{:?}", c.problems);
    assert_eq!(c.index.len(), 2);
    assert!(c.index.iter().any(|f| f.rel == "idx-1/.cache/2/pa"));

    // The reduction is labeled: the original's SHA-256 and the versions kept,
