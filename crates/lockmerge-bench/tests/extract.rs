//! Tests of `survey` and `extract` on a small repository built here with the
//! `git` binary. They never touch a real repository or the network.

use lockmerge_bench::case::load_case;
use lockmerge_bench::classify::Kind;
use lockmerge_bench::extract::{ExtractOpts, extract};
use lockmerge_bench::oracle::CargoOracle;
use lockmerge_bench::scan::{Source, ensure_clone, survey};
use lockmerge_bench::util::{TempDir, git_isolated, run};
use std::cell::Cell;
use std::collections::BTreeMap;
use std::fs;
use std::path::{Path, PathBuf};
use std::time::Duration;
use toml_edit::DocumentMut;

const HEAD: &str = "# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n\n";

/// `app` depends on the path package `member` and on every registry package.
fn lock(pkgs: &[&str]) -> String {
    let mut s = String::from(HEAD);
    s.push_str(
        "[[package]]\nname = \"app\"\nversion = \"0.1.0\"\ndependencies = [\n \"member\",\n",
    );
    for n in pkgs {
        s.push_str(&format!(" \"{n}\",\n"));
    }
    s.push_str("]\n\n[[package]]\nname = \"member\"\nversion = \"0.1.0\"\n");
    for n in pkgs {
        s.push_str(&format!(
            "\n[[package]]\nname = \"{n}\"\nversion = \"1.0.0\"\nsource = \"registry+x\"\nchecksum = \"{n}\"\n"
        ));
    }
    s
}

const MIT: &str = "MIT License\n\nPermission is hereby granted, free of charge, to any person obtaining a copy\nof this software and associated documentation files.\n";
const APACHE: &str = "Apache License\nVersion 2.0, January 2004\n";

struct Repo {
    dir: TempDir,
    tick: Cell<u32>,
}

impl Repo {
    fn new() -> Repo {
        let r = Repo {
            dir: TempDir::new("srcrepo").unwrap(),
            tick: Cell::new(0),
        };
        r.git(&["init", "-q", "-b", "main"]);
        r.git(&["config", "commit.gpgsign", "false"]);
        r
    }

    fn path(&self) -> &Path {
        self.dir.path()
    }

    /// Runs git; every call has a later date than the one before, so history
    /// is ordered by date.
    fn try_git(&self, args: &[&str]) -> bool {
        self.tick.set(self.tick.get() + 1);
        let date = format!(
            "2000-01-01T00:{:02}:{:02}+0000",
            self.tick.get() / 60,
            self.tick.get() % 60
        );
        let mut cmd = git_isolated(self.path());
        cmd.args(args)
            .env("GIT_AUTHOR_DATE", &date)
            .env("GIT_COMMITTER_DATE", &date);
        run(cmd, Duration::from_secs(60)).unwrap().ok()
    }

    fn git(&self, args: &[&str]) {
        assert!(self.try_git(args), "git {args:?} failed");
    }

    fn out(&self, args: &[&str]) -> String {
        let mut cmd = git_isolated(self.path());
        cmd.args(args);
        let r = run(cmd, Duration::from_secs(60)).unwrap();
        assert!(r.ok(), "git {args:?}: {}", r.stderr_text());
        String::from_utf8_lossy(&r.stdout).trim().to_string()
    }

    fn write(&self, rel: &str, content: &str) {
        let p = self.path().join(rel);
        fs::create_dir_all(p.parent().unwrap()).unwrap();
        fs::write(p, content).unwrap();
    }

    fn commit(&self, msg: &str) {
        self.git(&["add", "-A"]);
        self.git(&["commit", "-q", "-m", msg]);
    }

    fn head(&self) -> String {
        self.out(&["rev-parse", "HEAD"])
    }

    /// Merges `other` into the current branch. A text conflict is resolved
    /// by writing `resolution` to the lockfile.
    fn merge(&self, other: &str, resolution: &str) -> String {
        if !self.try_git(&["merge", "--no-ff", "--no-edit", other]) {
            self.write("Cargo.lock", resolution);
            self.commit("resolve");
        }
        self.head()
    }
}

/// The history of the scenario. Returns the repository and the merge commits
/// by name.
fn scenario() -> (Repo, BTreeMap<&'static str, String>) {
    let r = Repo::new();
    let mut m = BTreeMap::new();
    r.write("LICENSE-MIT", MIT);
    r.write("LICENSE-APACHE", APACHE);
    r.write("README", "readme\n");
    r.commit("root");
    let root = r.head();

    // Both branches add the lockfile: not a modify/modify case.
    r.git(&["checkout", "-q", "-b", "addA"]);
    r.write(
        "Cargo.toml",
        "[workspace]\nmembers = [\"crates/*\"]\n[package]\nname = \"app\"\n",
    );
    r.write(
        "crates/member/Cargo.toml",
        "[package]\nname = \"member\"\nversion = \"0.1.0\"\n",
    );
    r.write(
        "crates/other/Cargo.toml",
        "[package]\nname = \"other\"\nversion = \"0.1.0\"\n",
    );
    r.write("Cargo.lock", &lock(&["pa"]));
    r.commit("add lock A");
    r.git(&["checkout", "-q", "-b", "addB", &root]);
    r.write("Cargo.lock", &lock(&["pa", "pb"]));
    r.commit("add lock B");
    r.git(&["checkout", "-q", "addA"]);
    m.insert("add/add", r.merge("addB", &lock(&["pa", "pb"])));
    r.git(&["checkout", "-q", "-B", "main"]);
    let base = r.head();

    // A reachable case, and an older one with the same set of changed
    // packages: the newer one is kept and the older one is a duplicate.
    let mut base = base;
    for (name, tag) in [("dup", "a2"), ("reachable", "a1")] {
        r.git(&["checkout", "-q", "-B", &format!("{tag}x"), &base]);
        r.write("Cargo.lock", &lock(&["pa", "pb", "pc"]));
        r.write(
            "crates/member/Cargo.toml",
            "[package]\nname = \"member\"\nversion = \"0.2.0\"\n",
        );
        r.commit("ours adds pc");
        r.git(&["checkout", "-q", "-B", &format!("{tag}y"), &base]);
        r.write("Cargo.lock", &lock(&["pa", "pb", "pd"]));
        r.commit("theirs adds pd");
        r.git(&["checkout", "-q", &format!("{tag}x")]);
        // The committed resolution is valid but not canonical: a trailing
        // comment. The fixture must keep it, byte for byte.
        let resolution = format!("{}# merged by hand\n", lock(&["pa", "pb", "pc", "pd"]));
        m.insert(name, r.merge(&format!("{tag}y"), &resolution));
        r.git(&["checkout", "-q", "-B", "main"]);
        // Back to the starting lockfile, so the next case has the same base.
        r.write("Cargo.lock", &lock(&["pa", "pb"]));
        r.write(
            "crates/member/Cargo.toml",
            "[package]\nname = \"member\"\nversion = \"0.1.0\"\n",
        );
        r.commit("reset");
        base = r.head();
    }

    // A re-resolved case: the committed resolution has `pg`, which neither
    // side had.
    r.git(&["checkout", "-q", "-B", "bx", &base]);
    r.write("Cargo.lock", &lock(&["pa", "pb", "pe"]));
    r.commit("ours adds pe");
    r.git(&["checkout", "-q", "-B", "by", &base]);
    r.write("Cargo.lock", &lock(&["pa", "pb", "pf"]));
    r.commit("theirs adds pf");
    r.git(&["checkout", "-q", "bx"]);
    m.insert(
        "re-resolved",
        r.merge("by", &lock(&["pa", "pb", "pe", "pf", "pg"])),
    );
    r.git(&["checkout", "-q", "-B", "main"]);

    // An octopus merge.
    for n in ["o1", "o2", "o3"] {
        r.git(&["checkout", "-q", "-B", n, "main"]);
        r.write(&format!("{n}.txt"), "x\n");
        r.commit(n);
    }
    r.git(&["checkout", "-q", "main"]);
    assert!(r.try_git(&["merge", "--no-ff", "--no-edit", "o1", "o2", "o3"]));
    m.insert("octopus", r.head());

    // A criss-cross: two merges whose merge bases are two commits.
    r.git(&["checkout", "-q", "-B", "x", "main"]);
    r.write("xfile", "x\n");
    r.commit("x1");
    let x1 = r.head();
    r.git(&["checkout", "-q", "-B", "y", "main"]);
    r.write("yfile", "y\n");
    r.commit("y1");
    let y1 = r.head();
    r.git(&["checkout", "-q", "x"]);
    r.git(&["merge", "--no-ff", "--no-edit", &y1]);
    r.git(&["checkout", "-q", "y"]);
    r.git(&["merge", "--no-ff", "--no-edit", &x1]);
    r.git(&["checkout", "-q", "x"]);
    m.insert("criss-cross", r.merge("y", ""));
    (r, m)
}

fn source(r: &Repo, max_cases: usize) -> Source {
    Source {
        name: "t-repo".into(),
        url: r.path().to_string_lossy().into_owned(),
        ecosystem: "cargo".into(),
        lockfiles: vec!["Cargo.lock".into()],
        revision: r.head(),
        max_cases,
        max_file_bytes: 1_000_000,
        license: None,
    }
}

fn opts(out: &TempDir, cache: &TempDir) -> ExtractOpts {
    ExtractOpts {
        out: out.path().to_path_buf(),
        cache: cache.path().to_path_buf(),
        date: "2026-11-20".into(),
    }
}

fn index(out: &TempDir) -> BTreeMap<String, String> {
    let text = fs::read_to_string(out.path().join("cargo/INDEX.toml")).unwrap();
    let doc: DocumentMut = text.parse().unwrap();
    doc["merge"]
        .as_array_of_tables()
        .unwrap()
        .iter()
        .map(|t| {
            (
                t["merge_commit"].as_str().unwrap().to_string(),
                t["result"].as_str().unwrap().to_string(),
            )
        })
        .collect()
}

fn case_dir(out: &TempDir, merge: &str) -> PathBuf {
    out.path().join("cargo/t-repo").join(&merge[..12])
}

#[test]
fn extract_writes_exact_bytes_manifests_and_skips_with_reasons() {
    let (repo, m) = scenario();
    let (out, cache) = (TempDir::new("out").unwrap(), TempDir::new("cache").unwrap());
    let summary = extract(&source(&repo, 10), &opts(&out, &cache)).unwrap();
    assert!(summary.contains("MIT OR Apache-2.0"), "{summary}");

    // Every considered merge is listed, with the reason it was skipped.
    let idx = index(&out);
    assert_eq!(idx[&m["reachable"]], "case:reachable");
    assert_eq!(idx[&m["re-resolved"]], "case:re-resolved");
    assert_eq!(idx[&m["dup"]], "skipped:duplicate-change-set");
    assert_eq!(idx[&m["add/add"]], "skipped:not-modify-modify");
    assert_eq!(idx[&m["octopus"]], "skipped:octopus");
    assert_eq!(idx[&m["criss-cross"]], "skipped:multi-base");

    // Byte exactness, with the non-canonical trailing comment kept.
    let dir = case_dir(&out, &m["reachable"]);
    assert_eq!(
        fs::read_to_string(dir.join("base")).unwrap(),
        lock(&["pa", "pb"])
    );
    assert_eq!(
        fs::read_to_string(dir.join("ours")).unwrap(),
        lock(&["pa", "pb", "pc"])
    );
    assert_eq!(
        fs::read_to_string(dir.join("theirs")).unwrap(),
        lock(&["pa", "pb", "pd"])
    );
    assert_eq!(
        fs::read_to_string(dir.join("expected")).unwrap(),
        format!("{}# merged by hand\n", lock(&["pa", "pb", "pc", "pd"]))
    );

    // Manifests: the root and the path package, per side; not the unrelated one.
    let member = |side: &str| {
        fs::read_to_string(dir.join(format!("manifests/{side}/crates/member/Cargo.toml"))).unwrap()
    };
    assert!(member("base").contains("0.1.0"));
    assert!(member("ours").contains("0.2.0"));
    assert!(member("theirs").contains("0.1.0"));
    for side in ["base", "ours", "theirs"] {
        assert!(dir.join(format!("manifests/{side}/Cargo.toml")).is_file());
        assert!(
            !dir.join(format!("manifests/{side}/crates/other/Cargo.toml"))
                .exists()
        );
    }

    // The fixture loads, its hashes hold, and its class is recorded by rule.
    let c = load_case("cargo", "cargo/t-repo/x", &dir).unwrap();
    assert!(c.problems.is_empty(), "{:?}", c.problems);
    assert_eq!(c.meta.kind, Kind::Reachable);
    assert_eq!(c.meta.license, "MIT OR Apache-2.0");
    assert_eq!(c.meta.merge_commit, m["reachable"]);
    let rr = load_case(
        "cargo",
        "cargo/t-repo/y",
        &case_dir(&out, &m["re-resolved"]),
    )
    .unwrap();
    assert!(rr.problems.is_empty(), "{:?}", rr.problems);
    assert_eq!(
        (rr.meta.kind, rr.meta.foreign_count),
        (Kind::ReResolved, Some(1))
    );

    // License texts sit next to the repository directory.
    assert_eq!(
        fs::read_to_string(out.path().join("cargo/t-repo/LICENSE-MIT")).unwrap(),
        MIT
    );
}

#[test]
fn the_re_resolved_quota_keeps_the_headline_denominator_from_starving() {
    let (repo, m) = scenario();
    let (out, cache) = (TempDir::new("out").unwrap(), TempDir::new("cache").unwrap());
    // One case wanted: half of one is zero re-resolved cases. The newer
    // re-resolved merge is skipped and the reachable one is taken; the walk
    // stops there, so older merges are never considered.
    extract(&source(&repo, 1), &opts(&out, &cache)).unwrap();
    let idx = index(&out);
    assert_eq!(idx[&m["re-resolved"]], "skipped:re-resolved-quota");
    assert_eq!(idx[&m["reachable"]], "case:reachable");
    assert!(!idx.contains_key(&m["add/add"]));
    assert!(!case_dir(&out, &m["re-resolved"]).exists());
}

#[test]
fn a_second_run_keeps_the_entries_of_other_repositories() {
    let (repo, m) = scenario();
    let (out, cache) = (TempDir::new("out").unwrap(), TempDir::new("cache").unwrap());
    fs::create_dir_all(out.path().join("cargo")).unwrap();
    fs::write(
        out.path().join("cargo/INDEX.toml"),
        "[[merge]]\nrepository = \"https://example.invalid/other\"\nmerge_commit = \"abc\"\nlockfile_path = \"Cargo.lock\"\nresult = \"skipped:octopus\"\n",
    )
    .unwrap();
    extract(&source(&repo, 10), &opts(&out, &cache)).unwrap();
    extract(&source(&repo, 10), &opts(&out, &cache)).unwrap();
    let idx = index(&out);
    assert_eq!(idx["abc"], "skipped:octopus");
    assert_eq!(idx[&m["reachable"]], "case:reachable");
    assert_eq!(idx.len(), 1 + 8);
}

#[test]
fn survey_counts_candidates_and_writes_no_fixtures() {
    let (repo, _) = scenario();
    let cache = TempDir::new("cache").unwrap();
    let src = source(&repo, 10);
    let clone = cache.path().join("t-repo.git");
    ensure_clone(&src, &clone).unwrap();
    let line = survey(&clone, &src, &CargoOracle).unwrap();
    // The duplicate is still a candidate: survey does not diversify.
    assert!(
        line.contains("3 candidates (reachable 2, re-resolved 1)"),
        "{line}"
    );
    assert!(line.contains("skipped:multi-base 1"), "{line}");
    assert!(line.contains("skipped:octopus 1"), "{line}");
}

#[test]
fn a_license_outside_the_list_is_not_extracted() {
    let (repo, _) = scenario();
    let (out, cache) = (TempDir::new("out").unwrap(), TempDir::new("cache").unwrap());
    let mut src = source(&repo, 10);
    // Unrecognizable license files at the pin, and a declared license that is
    // not allowed.
    repo.git(&["checkout", "-q", "x"]);
    repo.write("LICENSE-MIT", "GNU GENERAL PUBLIC LICENSE\nVersion 3\n");
    repo.write("LICENSE-APACHE", "GNU GENERAL PUBLIC LICENSE\nVersion 3\n");
    repo.commit("relicense");
    src.revision = repo.head();
    src.license = Some("GPL-3.0-only".into());
    let err = extract(&src, &opts(&out, &cache)).unwrap_err();
    assert!(err.contains("outside the allowed list"), "{err}");
    assert!(!out.path().join("cargo/t-repo").exists());
    // No declaration at all: the owner has to decide.
    src.license = None;
    let (out2, cache2) = (TempDir::new("out").unwrap(), TempDir::new("cache").unwrap());
    let err = extract(&src, &opts(&out2, &cache2)).unwrap_err();
    assert!(err.contains("no license recognized"), "{err}");
}

#[test]
fn a_declared_license_that_contradicts_the_files_is_refused() {
    let (repo, _) = scenario();
    let (out, cache) = (TempDir::new("out").unwrap(), TempDir::new("cache").unwrap());
    let mut src = source(&repo, 10);
    src.license = Some("ISC".into());
    let err = extract(&src, &opts(&out, &cache)).unwrap_err();
    assert!(err.contains("license files at the pin show"), "{err}");
}
