// Squash-merged pull requests (`squash_prs`).

/// How the squash scenario differs from the plain accepted case.
#[derive(Default)]
struct Squash {
    /// The squash commit changes a file the pull request did not.
    extra_change: bool,
    /// The default branch and the pull request both change `src.rs`.
    overlap: bool,
    /// The default branch and the pull request both change `Cargo.toml`, in
    /// different hunks, and the squash commit is the clean merge.
    hunks: bool,
    /// With `hunks`: the squash commit also hand-edits `Cargo.toml` further.
    fixup: bool,
    /// With `hunks`: both sides change the same line of `Cargo.toml`.
    same_hunk: bool,
    /// With `hunks`: main splits `z/{b,c}` into `y/b` and `w/c`, the pull
    /// request adds `z/d`, and the squash keeps those locations. Git reports a
    /// directory rename conflict with no conflicted file entry.
    dir_split: bool,
    /// A second commit on the default branch also names the pull request.
    second_commit: bool,
    /// The pull request leaves the lockfile alone.
    lock_untouched: bool,
    /// The subject of the squash commit.
    subject: Option<&'static str>,
}

struct Landed {
    repo: Repo,
    squash: String,
    ours: String,
    head: String,
}

/// A `Cargo.toml` with two lines far enough apart to be separate hunks.
fn manifest(top: Option<&str>, bottom: Option<&str>) -> String {
    format!(
        "[package]\nname = \"{}\"\n\n[a]\n[b]\n[c]\n[d]\n[e]\n[f]\n[g]\n[h]\n\n[dependencies]\nz = \"{}\"\n",
        top.unwrap_or("app"),
        bottom.unwrap_or("1")
    )
}

/// Moves `z/b` and `z/c` into two different directories.
fn split_z(r: &Repo) {
    r.write("y/b", "b\n");
    r.write("w/c", "c\n");
    for f in ["z/b", "z/c"] {
        let _ = fs::remove_file(r.path().join(f));
    }
}

/// A repository where pull request 7 adds `pr1` to the lockfile and the
/// default branch adds `m1`, so plain git conflicts, and the pull request is
/// squash-merged (the lockfile resolved by hand) with `refs/pull/7/head` left
/// pointing at its head.
fn squash_scenario(v: Squash) -> Landed {
    let r = Repo::new();
    r.write("LICENSE-MIT", MIT);
    r.write("Cargo.toml", &manifest(None, None));
    r.write(
        "crates/member/Cargo.toml",
        "[package]\nname = \"member\"\nversion = \"0.1.0\"\n",
    );
    r.write("src.rs", "one\n");
    r.write("other.rs", "o\n");
    r.write("z/b", "b\n");
    r.write("z/c", "c\n");
    r.write("Cargo.lock", &lock(&["p1", "p2"]));
    r.commit("root");
    r.git(&["checkout", "-q", "-B", "pr"]);
    if !v.lock_untouched {
        r.write("Cargo.lock", &lock(&["p1", "p2", "pr1"]));
    }
    r.write("pr.rs", "pr\n");
    if v.overlap {
        r.write("src.rs", "pr version\n");
    }
    if v.hunks {
        r.write("Cargo.toml", &manifest(Some("pr"), None));
    }
    if v.dir_split {
        r.write("z/d", "d\n");
    }
    r.commit("pr work");
    let head = r.head();
    r.git(&["checkout", "-q", "-B", "main", "HEAD~1"]);
    r.write("Cargo.lock", &lock(&["p1", "p2", "m1"]));
    if v.overlap {
        r.write("src.rs", "main version\n");
    }
    if v.hunks {
        let m = if v.same_hunk {
            manifest(Some("main"), None)
        } else {
            manifest(None, Some("2"))
        };
        r.write("Cargo.toml", &m);
    }
    if v.dir_split {
        split_z(&r);
    }
    r.commit("main work");
    let ours = r.head();
    // The squash merge: the pull request's changes as one commit.
    r.try_git(&["merge", "--squash", "pr"]);
    if !v.lock_untouched {
        r.write("Cargo.lock", &lock(&["p1", "p2", "m1", "pr1"]));
    }
    if v.overlap {
        r.write("src.rs", "merged\n");
    }
    if v.hunks {
        let m = if v.same_hunk {
            manifest(Some("hand"), None)
        } else if v.fixup {
            manifest(Some("pr"), Some("3"))
        } else {
            manifest(Some("pr"), Some("2"))
        };
        r.write("Cargo.toml", &m);
    }
    if v.dir_split {
        split_z(&r);
        r.write("z/d", "d\n");
    }
    if v.extra_change {
        r.write("other.rs", "changed\n");
    }
    r.commit(v.subject.unwrap_or("Add pr1 (#7)"));
    let squash = r.head();
    if v.second_commit {
        r.write("again.rs", "x\n");
        r.commit("Follow up (#7)");
    }
    r.git(&["update-ref", "refs/pull/7/head", &head]);
    Landed {
        repo: r,
        squash,
        ours,
        head,
    }
}

fn squash_source(l: &Landed) -> Source {
    let mut s = source(&l.repo, 10);
    s.squash_prs = true;
    s
}

fn index_of(out: &TempDir) -> BTreeMap<String, String> {
    let text = fs::read_to_string(out.path().join("cargo/INDEX.toml")).unwrap();
    // No `[[merge]]` table at all when nothing was considered.
    if text.contains("[[merge]]") {
        index(out)
    } else {
        BTreeMap::new()
    }
}

fn run_squash(v: Squash) -> (Landed, BTreeMap<String, String>, TempDir) {
    let l = squash_scenario(v);
    let (out, cache) = (TempDir::new("out").unwrap(), TempDir::new("cache").unwrap());
    extract(&squash_source(&l), &opts(&out, &cache)).unwrap();
    let idx = index_of(&out);
    (l, idx, out)
}

