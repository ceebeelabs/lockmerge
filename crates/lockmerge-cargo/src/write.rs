//! The canonical writer: Cargo's own text for versions 3 and 4, written by this
//! code and never by a TOML library (ADR 0008 decision 11, ADR 0014).
//!
//! Layout (`docs/formats/cargo-lock.md` section 5): the two header comment
//! lines, `version = N`, then per package a blank line and `[[package]]` with
//! `name`, `version`, `source`, `checksum` and `dependencies` in that order
//! (the last a multi-line array, one space of indent, a comma after every
//! entry). Packages are in id order; each package's edges are in the order of their text
//! fields (name, version text, source), as Cargo sorts them. The file ends
//! with one newline. Edges are as short as Cargo writes them.

use crate::model::{Id, Package, edge_form, resolve_edge};

const HEADER: &str =
    "# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\n";

/// A string the writer emits between basic quotes without escaping. Inputs
/// with anything else are refused at parse time, so merged text always passes.
pub fn is_plain(s: &str) -> bool {
    !s.is_empty() && !s.chars().any(|c| c == '"' || c == '\\' || c.is_control())
}

/// Writes `items`, which must be in id order, as a version `version` lockfile.
/// `None` if the set cannot be written with certainty: it is empty, a string
/// needs escaping, an edge has no known Cargo form, or an edge's text would
/// not resolve back to its target.
pub fn render(version: u8, items: &[(&Id, &Package)]) -> Option<Vec<u8>> {
    if items.is_empty() {
        return None;
    }
    let ids: Vec<&Id> = items.iter().map(|(id, _)| *id).collect();
    let mut out = String::from(HEADER);
    out.push_str(&format!("version = {version}\n"));
    for (id, pkg) in items {
        out.push_str("\n[[package]]\n");
        field(&mut out, "name", &id.name)?;
        field(&mut out, "version", &id.version.to_string())?;
        if let Some(source) = &id.source {
            field(&mut out, "source", source)?;
        }
        if let Some(checksum) = &pkg.checksum {
            field(&mut out, "checksum", checksum)?;
        }
        if !pkg.edges.is_empty() {
            out.push_str("dependencies = [\n");
            let mut forms = Vec::new();
            for target in &pkg.edges {
                let form = edge_form(&ids, target)?;
                let text = form.text();
                // The text must name exactly the target in this very file.
                if resolve_edge(ids.iter().copied(), &text) != Ok(target) || !is_plain(&text) {
                    return None;
                }
                forms.push(form);
            }
            forms.sort();
            for form in forms {
                out.push_str(&format!(" \"{}\",\n", form.text()));
            }
            out.push_str("]\n");
        }
    }
    Some(out.into_bytes())
}

fn field(out: &mut String, key: &str, value: &str) -> Option<()> {
    if !is_plain(value) {
        return None;
    }
    out.push_str(&format!("{key} = \"{value}\"\n"));
    Some(())
}
